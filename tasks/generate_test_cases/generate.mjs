import { compile, compileModule } from "svelte/compiler";
import { readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { stripTypeScriptTypes } from "node:module";
import { transformSync as oxcTransformSync } from "oxc-transform";

function stripTsToJs(source) {
  stripTypeScriptTypes(source, { mode: "strip" });
  return oxcTransformSync("input.ts", source, {
    typescript: { onlyRemoveTypeImports: true },
  }).code;
}

const inputPath = process.env.INPUT_FILE || "/dev/stdin";
const files = JSON.parse(readFileSync(inputPath, "utf8"));
const quickCheckOverride = process.env.QUICK_CHECK_CONFIG
  ? JSON.parse(process.env.QUICK_CHECK_CONFIG)
  : null;
const results = {};
for (const file of files) {
  const text = readFileSync(file, "utf8");
  const isModule = file.endsWith('.svelte.js') || file.endsWith('.svelte.ts');
  const isDiagnosticCase = file.includes('tasks/diagnostic_tests/cases/');

  const caseDir = dirname(file);
  const configPath = join(caseDir, "config.json");
  let caseConfig = {};
  if (existsSync(configPath)) {
    caseConfig = JSON.parse(readFileSync(configPath, "utf8"));
  }
  if (quickCheckOverride) {
    caseConfig = { ...caseConfig, ...quickCheckOverride };
  }

  if (isDiagnosticCase) {
    results[file] = {
      diagnostics: generateDiagnostics(text, caseConfig, isModule),
    };
    continue;
  }

  const compileConfig = {
    discloseVersion: false,
    dev: false,
    name: "App",
    modernAst: true,
    runes: true,
    ...caseConfig,
  };
  if (compileConfig.runes === null) {
    delete compileConfig.runes;
  }
  if (compileConfig.name === null) {
    delete compileConfig.name;
  }
  const isTsModule = isModule && file.endsWith('.svelte.ts');
  const moduleSource = isTsModule ? stripTsToJs(text) : text;
  const moduleFilename = isTsModule ? 'case.svelte.ts' : 'case.svelte.js';

  const compileCell = (dev, generate) =>
    isModule
      ? compileModule(moduleSource, {
          filename: moduleFilename,
          ...caseConfig,
          dev,
          ...(generate ? { generate } : {}),
        })
      : compile(text, { ...compileConfig, dev, ...(generate ? { generate } : {}) });

  if (quickCheckOverride) {
    const dev = compileConfig.dev === true;
    const result = compileCell(dev);
    let code = result.js.code;
    if (isModule) code = stripVersionComment(code);
    results[file] = { js: code, css: result.css?.code ?? null };
    continue;
  }

  const prod = compileCell(false);
  const dev = compileCell(true);
  let js = prod.js.code;
  let jsDev = dev.js.code;
  let jsServer = null;
  let jsServerDev = null;
  try {
    jsServer = compileCell(false, "server").js.code;
  } catch {}
  try {
    jsServerDev = compileCell(true, "server").js.code;
  } catch {}
  if (isModule) {
    js = stripVersionComment(js);
    jsDev = stripVersionComment(jsDev);
    if (jsServer) jsServer = stripVersionComment(jsServer);
    if (jsServerDev) jsServerDev = stripVersionComment(jsServerDev);
  }
  results[file] = { js, jsDev, jsServer, jsServerDev, css: prod.css?.code ?? null };
}

function stripVersionComment(code) {
  return code.replace(/^\/\*.*?generated by Svelte.*?\*\/\n/, "");
}
console.log(JSON.stringify(results));

function generateDiagnostics(source, caseConfig, isModule = false) {
  const compileConfig = {
    discloseVersion: false,
    dev: false,
    name: "App",
    modernAst: true,
    runes: true,
    ...caseConfig,
  };
  if (compileConfig.runes === null) {
    delete compileConfig.runes;
  }
  if (compileConfig.name === null) {
    delete compileConfig.name;
  }
  try {
    if (isModule) {
      const result = compileModule(source, {
        dev: compileConfig.dev,
        filename: "case.svelte.js",
      });
      return result.warnings.map((warning) => normalizeDiagnostic(warning, "warning"));
    }
    const result = compile(source, compileConfig);
    return result.warnings.map((warning) => normalizeDiagnostic(warning, "warning"));
  } catch (error) {
    return [normalizeDiagnostic(error, "error")];
  }
}

function normalizeDiagnostic(diagnostic, severity) {
  return {
    severity,
    code: diagnostic.code,
    start: diagnostic.position?.[0] ?? diagnostic.start?.character ?? 0,
    end: diagnostic.position?.[1] ?? diagnostic.end?.character ?? diagnostic.position?.[0] ?? 0,
  };
}
